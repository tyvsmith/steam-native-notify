#!/usr/bin/env node
/**
 * Generate docs/notification-types.md: every notification type, whether Steam
 * gives it a click action, and whether this plugin can derive one.
 *
 * Three sources, all cited in the output so a future reader can re-check them:
 *   proto      vendor/steammessages_clientnotificationtypes.proto
 *   changelog  Steam Client Update, 14 June 2023
 *   observed   clicked on this machine
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const proto = readFileSync(join(root, 'vendor', 'steammessages_clientnotificationtypes.proto'), 'utf8');

const enumBody = /enum EClientNotificationType \{([\s\S]*?)\n\}/.exec(proto)[1];
const types = [...enumBody.matchAll(/k_EClientNotificationType_(\w+)\s*=\s*(\d+)/g)]
	.map(([, name, index]) => ({ name, index: Number(index) }))
	.sort((a, b) => a.index - b.index);

const messages = {};
for (const [, name, body] of proto.matchAll(/message (\w+) \{([\s\S]*?)\n\}/g)) {
	messages[name] = [...body.matchAll(/(?:optional|required|repeated)\s+[\w.]+\s+(\w+)\s*=\s*\d+/g)]
		.map((m) => m[1]);
}

// Steam Client Update, 14 June 2023: "Added support for notification types shown
// in the Desktop Client and Mobile app: Wishlist, Trade Offer, Steam Turn, Help
// Request, Major Sale, and Comment" alongside "Fixed inability to click on Steam
// notification toasts (eg. wishlist, comment)."
const CHANGELOG_CLICKABLE = new Set([
	'Wishlist', 'TradeOffer', 'AsyncGame', 'HelpRequest', 'MajorSale', 'Comment',
]);

// Clicked on a real client and seen to do nothing.
const OBSERVED_INERT = new Set(['DownloadCompleted', 'FriendOnline']);

const rows = types
	.filter((t) => t.name !== 'Invalid')
	.map((t) => {
		const message = `CClientNotification${t.name}`;
		const fields = messages[message] ?? null;
		const hasUrl = fields?.includes('response_steamurl') ?? false;

		let steam, us, note;
		if (hasUrl) {
			steam = 'yes';
			us = 'yes';
			note = 'carries `response_steamurl`';
		} else if (CHANGELOG_CLICKABLE.has(t.name)) {
			steam = 'yes';
			us = 'no';
			note = 'clickable per changelog, but no payload message to route from';
		} else if (OBSERVED_INERT.has(t.name)) {
			steam = 'no';
			us = 'no';
			note = 'clicked and confirmed inert';
		} else if (!fields) {
			steam = 'unknown';
			us = 'no';
			note = 'no payload message';
		} else {
			steam = 'unlikely';
			us = 'no';
			note = `fields: ${fields.join(', ')}`;
		}
		return { ...t, steam, us, note };
	});

const count = (p) => rows.filter(p).length;

const doc = `<!-- GENERATED by tools/gen-types-table.mjs. Do not edit; run \`npm run gen:table\`. -->

# Notification types

Every value of \`EClientNotificationType\`, whether Steam gives its toast a click
action, and whether this plugin can derive one.

Sources: the vendored \`.proto\`; the [Steam Client Update of 14 June 2023](https://store.steampowered.com/oldnews/195171),
which added the clickable set; and clicks performed on a real client.

- **${count((r) => r.us === 'yes')}** type routes here, the only one Steam declares an action for.
- **${count((r) => r.steam === 'yes' && r.us === 'no')}** types Steam makes clickable that this cannot reach: they have no
  payload message, so their routing lives outside this schema.
- **${count((r) => !messages['CClientNotification' + r.name])}** of ${rows.length} types carry no payload message at all.

| # | Type | Steam acts? | We route? | Basis |
|---|---|---|---|---|
${rows.map((r) => `| ${r.index} | \`${r.name}\` | ${r.steam} | ${r.us} | ${r.note} |`).join('\n')}

## Reading this

**yes** — verified from the schema or Valve's changelog.
**no** — verified inert by clicking the real toast.
**unlikely** — has a payload message, but nothing route-shaped in it, and Valve
did not list it as clickable. Not individually tested.
**unknown** — no payload message and not on Valve's list; nothing to go on.
`;

mkdirSync(join(root, 'docs'), { recursive: true });
writeFileSync(join(root, 'docs', 'notification-types.md'), doc);
console.log(`generated docs/notification-types.md (${rows.length} types)`);
